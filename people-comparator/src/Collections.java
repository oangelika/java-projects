public class Collections {
    // list:
// ArrayList: Реализация основана на массиве, обеспечивает быстрый доступ к элементам, но медленные вставки/удаления.
// LinkedList: Реализация основана на двусвязном списке, обеспечивает эффективные вставки/удаления, но медленный доступ к элементам.

   // set:
// HashSet: Реализация на основе хэш-таблицы, обеспечивает постоянное время доступа, но не гарантирует порядок элементов.
// TreeSet: Реализация на основе красно-черного дерева, обеспечивает элементы в отсортированном порядке
// LinkedHashSet: Связывает элементы хэш-таблицей и двусвязным списком, сохраняя порядок вставки.

    // map:
// HashMap: Реализация отображения ключей на значения с использованием хэш-таблицы.
// TreeMap: Реализация на основе красно-черного дерева, обеспечивает отсортированный порядок ключей.
// LinkedHashMap: Связывает отображения хэш-таблицей и двусвязным списком, сохраняя порядок вставки.

    // queue:
// PriorityQueue: Реализация очереди с приоритетами, где элементы извлекаются в порядке их приоритетов.
// LinkedList: Реализация основана на двусвязном списке, обеспечивает эффективные вставки/удаления, но медленный доступ к элементам.



}
